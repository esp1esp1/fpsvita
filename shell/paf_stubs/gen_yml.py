#!/usr/bin/env python3
"""Generate a vita-libs-gen-2 yml for ScePaf from ScePaf-RE's .emd files.

ScePaf-RE (https://github.com/VitaArchive/ScePaf-RE) ships Sony-format .emd
export lists with the real mangled names. A Sony NID is the first four bytes,
little-endian, of SHA-1(name + nidsuffix), so the names are enough.

Usage: gen_yml.py <ScePaf-RE/lib dir> > ScePafRE.yml
"""
import hashlib, re, struct, sys, glob, os

LIBS = ['ScePafCommon', 'ScePafGraphics', 'ScePafMisc', 'ScePafResource',
        'ScePafStdc', 'ScePafThread', 'ScePafToplevel', 'ScePafWidget']
MODULE_NID = 0xCD679177  # ScePaf, from vita-headers db/360/ScePaf.yml

# Exports ScePaf-RE's .emd lists do not name. NIDs taken from the stub archives
# in ScePaf-RE's lib/ (real firmware NIDs under its own names); verified on device.
EXTRA = {
    'ScePafCommon': {
        # paf::String::String(const char*) per those archives: constructs a string in
        # the firmware's own layout, which is what Plugin::InitParam needs.
        '_ZN3paf6StringC1EPKc': 0xaed94915,
    },
    'ScePafWidget': {
        # Widget::PlayAnimation / PlayAnimationReverse(Animation, cb, ud) per
        # those archives; PSVshellPlus imports them. ScePaf-RE's Widget::Show/Hide
        # (Timer variant) hash to NIDs this firmware does not export (a call
        # traps at pc=0), so show/hide go through these instead.
        '_ZN3paf6widget6Widget13PlayAnimationENS1_9AnimationEPFviPS1_iPvES4_': 0x44b22aca,
        '_ZN3paf6widget6Widget20PlayAnimationReverseENS1_9AnimationEPFviPS1_iPvES4_': 0xf1176acc,
    },
}

def nid(name, suffix):
    return struct.unpack('<I', hashlib.sha1((name + suffix).encode()).digest()[:4])[0]

out = ['# Generated by gen_yml.py from ScePaf-RE .emd files. Do not edit.',
       'version: 2', 'firmware: 3.60', 'modules:', '  ScePaf:',
       f'    nid: 0x{MODULE_NID:08X}', '    libraries:']
for lib in LIBS:
    t = open(os.path.join(sys.argv[1], lib + '.emd'), errors='replace').read()
    libnid = re.search(r'libnamenid: (0x[0-9A-Fa-f]+)', t).group(1)
    suffix = re.search(r'nidsuffix: "([^"]*)"', t).group(1)
    names = sorted(set(re.findall(r'function: (\S+)', t)))
    out += [f'      {lib}:', '        kernel: false', f'        nid: {libnid}', '        functions:']
    out += [f'          {n}: 0x{nid(n, suffix):08x}' for n in names]
    out += [f'          {n}: 0x{v:08x}' for n, v in sorted(EXTRA.get(lib, {}).items())]
print('\n'.join(out))
