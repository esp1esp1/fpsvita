#!/usr/bin/env python3
"""Generate shell/compat_data.h from the "Probably incompatible" table.

The table is the source of truth in docs/compatibility-list.md. The shell only
needs a title id and a short flag word, so this script extracts both and emits a
sorted C table. Run with --check in tests/run.sh to catch a stale header.
"""
import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LIST = ROOT / "docs" / "compatibility-list.md"
OUT = ROOT / "shell" / "compat_data.h"

ID_RE = re.compile(r"\bPCS[A-Z]\d{5}\b")

FLAGS = [
    ("SPEED", 1 << 0, ("faster", "double speed", "speed follows", "ignores a 60")),
    ("NOINPUT", 1 << 1, ("no input above",)),
    ("FREEZE", 1 << 2, ("freezes",)),
    ("SHAKE", 1 << 3, ("shakes",)),
    ("MENUS", 1 << 4, ("menus double speed", "ui and menus")),
    ("VIDEO", 1 << 5, ("videos break",)),
    ("SLOW", 1 << 6, ("slow motion below", "slower below", "slower at 20")),
]


def classify(text):
    text = text.lower()
    flags = 0
    for _name, bit, needles in FLAGS:
        if any(n in text for n in needles):
            flags |= bit
    return flags or (1 << 0)


def parse():
    lines = LIST.read_text(encoding="utf-8").splitlines()
    start = None
    for i, line in enumerate(lines):
        if line.strip() == "## Probably incompatible":
            start = i + 1
            break
    if start is None:
        raise SystemExit("section not found in " + str(LIST))

    entries = {}
    for line in lines[start:]:
        if line.startswith("## "):
            break
        if not line.startswith("|"):
            continue
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cells) < 3 or cells[0] == "Title" or set(cells[0]) <= {"-"}:
            continue
        ids = ID_RE.findall(cells[1])
        if not ids:
            continue
        flags = classify(cells[2])
        for tid in ids:
            entries[tid] = entries.get(tid, 0) | flags
    return entries


def render(entries):
    out = []
    out.append("/* Generated by tools/gen_compat.py from docs/compatibility-list.md.")
    out.append(" * Rows that share a title id (collections) OR their flags. */")
    out.append("#ifndef FPSVITA_COMPAT_DATA_H")
    out.append("#define FPSVITA_COMPAT_DATA_H")
    out.append("")
    out.append("enum {")
    for name, bit, _needles in FLAGS:
        out.append(f"\tFPSVITA_COMPAT_{name} = {bit}u,")
    out.append("};")
    out.append("")
    out.append("struct FpsvitaCompatEntry { const char *id; unsigned flags; };")
    out.append("")
    out.append("static const struct FpsvitaCompatEntry fpsvita_compat[] = {")
    for tid in sorted(entries):
        out.append(f'\t{{ "{tid}", {entries[tid]}u }},')
    out.append("};")
    out.append("static const unsigned fpsvita_compat_count =")
    out.append("\t(unsigned)(sizeof(fpsvita_compat) / sizeof(fpsvita_compat[0]));")
    out.append("")
    out.append("#endif")
    out.append("")
    return "\n".join(out)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="fail if the header is stale")
    ap.add_argument("--out", type=Path, default=OUT)
    a = ap.parse_args()
    text = render(parse())
    if a.check:
        current = a.out.read_text(encoding="utf-8") if a.out.exists() else ""
        if current != text:
            print(f"{a.out} is stale; run tools/gen_compat.py", file=sys.stderr)
            return 1
        print(f"{a.out} is up to date ({len(parse())} title ids)")
        return 0
    a.out.write_text(text, encoding="utf-8")
    print(f"wrote {a.out} ({len(parse())} title ids)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
